/* ============================================================
   OPEN ART — the REA-powered art-app cloning pipeline, in-app.
   Renders docs/research/open-art/pipeline.json (20 stages, 26
   tools) as an interactive runbook: pick a target URL, click any
   stage to copy its exact `node tools/rea/run.mjs` invocation,
   and track which stages have produced evidence on disk.
   Data is generated by scripts/gen-open-art-data.mjs — edit the
   pipeline JSON, not this file.
   ============================================================ */
import { useMemo, useState } from 'react';
import { OPEN_ART, type OpenArtStage, type OpenArtTool } from './lib/open-art-data';
import { SuiteIcon as Ic } from './suite-icons';

const PHASES: { label: string; ids: string[] }[] = [
  { label: 'Capture', ids: ['discover', 'capture-passive', 'capture-scenario', 'observe-session', 'observe-execution'] },
  { label: 'Extract', ids: ['analyze-bundle', 'export-scripts', 'trace-imports', 'recover-sources', 'static-graph'] },
  { label: 'Trace', ids: ['trace-feature', 'runtime-reconcile', 'network-decode', 'compare-captures', 'compare-apps'] },
  { label: 'Verify', ids: ['webmcp', 'event-listeners', 'source-attribution', 'verify', 'screenshot'] },
];

/* Build the shell command a stage would run against the target URL. */
function stageCommand(stage: OpenArtStage, target: string): string {
  const t = target.trim() || 'https://target.app';
  const tool = stage.tools[0];
  const inputs = tool?.required_inputs ?? [];
  const args: string[] = [];
  for (const inp of inputs) {
    if (inp === 'cdp_endpoint') args.push('--cdp-endpoint http://127.0.0.1:9222');
    else if (inp === 'url') args.push(`--url ${JSON.stringify(t)}`);
    else if (inp === 'origin') { try { args.push(`--origin ${new URL(t).origin}`); } catch { /* keep default */ } }
    else if (inp === 'bundle_path' || inp === 'script_paths') args.push(`--out evidence/${stage.id}`);
    else if (inp === 'output_dir') args.push(`--out evidence/${stage.id}`);
    else if (inp === 'seed') args.push('--seed <route-or-string>');
    else args.push(`--${inp.split('_').join('-')} <${inp}>`);
  }
  return `node tools/rea/run.mjs ${tool ? tool.cli : '<tool>'} ${args.join(' ')}`.trim();
}

export default function OpenArtPage({ onBack }: { onBack: () => void }) {
  const [target, setTarget] = useState('');
  const [selId, setSelId] = useState<string>(OPEN_ART.stages[0]?.id ?? '');
  const [copied, setCopied] = useState<string | null>(null);
  const [done, setDone] = useState<Record<string, boolean>>(() => {
    try { return JSON.parse(localStorage.getItem('cn_openart_done') || '{}'); } catch { return {}; }
  });
  const toggleDone = (id: string) => {
    setDone((d) => {
      const next = { ...d, [id]: !d[id] };
      try { localStorage.setItem('cn_openart_done', JSON.stringify(next)); } catch { /* private mode */ }
      return next;
    });
  };
  const sel = OPEN_ART.stages.find((s) => s.id === selId) ?? OPEN_ART.stages[0];
  const toolCount = useMemo(() => OPEN_ART.stages.reduce((a, s) => a + s.tools.length, 0), []);
  const doneCount = useMemo(() => OPEN_ART.stages.filter((s) => done[s.id]).length, [done]);

  const copy = async (text: string, key: string) => {
    try { await navigator.clipboard.writeText(text); setCopied(key); setTimeout(() => setCopied(null), 1400); } catch { /* no clipboard */ }
  };

  return (
    <div className="page-pad suite open-art">
      <div className="dir-top">
        <button className="lnk dir-back" onClick={onBack}><Ic name="back" size={14} /> Suite</button>
        <h1 className="home-h1 serif">Open Art</h1>
        <span className="dir-count">{OPEN_ART.stage_count} stages · {toolCount} REA tools</span>
      </div>

      <p className="oa-lede">
        Clone any AI-art web app's structure with <b>{OPEN_ART.source}</b>. Enter a target, walk the four phases,
        and each stage hands you the exact command plus where its evidence lands. Research only — understand the
        mechanics, then build our own.
      </p>

      <div className="oa-target">
        <input
          type="url"
          className="input"
          placeholder="Target app URL — e.g. https://openart.ai"
          value={target}
          onChange={(e) => setTarget(e.target.value)}
        />
        <span className={`oa-progress${doneCount === OPEN_ART.stage_count ? ' complete' : ''}`}>
          {doneCount}/{OPEN_ART.stage_count} stages evidenced
        </span>
      </div>

      {/* phase × stage board */}
      <div className="oa-board">
        {PHASES.map((ph) => (
          <div className="oa-phase card" key={ph.label}>
            <div className="oa-phase-h">{ph.label}</div>
            {ph.ids.map((id) => {
              const s = OPEN_ART.stages.find((x) => x.id === id);
              if (!s) return null;
              return (
                <button
                  key={s.id}
                  className={`oa-stage${selId === s.id ? ' on' : ''}${done[s.id] ? ' done' : ''}`}
                  onClick={() => setSelId(s.id)}
                  title={s.purpose}
                >
                  <span className="oa-dot" aria-hidden />
                  <span className="oa-stage-name">{s.id}</span>
                  <span className="oa-stage-tools">{s.tools.length} tool{s.tools.length === 1 ? '' : 's'}</span>
                </button>
              );
            })}
          </div>
        ))}
      </div>

      {/* selected stage detail */}
      {sel && (
        <div className="oa-detail card">
          <div className="oa-detail-h">
            <h2 className="home-h1">{sel.id}</h2>
            <label className="oa-check">
              <input type="checkbox" checked={!!done[sel.id]} onChange={() => toggleDone(sel.id)} />
              evidence captured
            </label>
          </div>
          <p className="oa-purpose">{sel.purpose}</p>

          <pre className="oa-cmd">
            <code>{stageCommand(sel, target)}</code>
            <button className="lnk oa-copy" onClick={() => copy(stageCommand(sel, target), 'main')}>
              {copied === 'main' ? 'copied ✓' : 'copy'}
            </button>
          </pre>

          <div className="oa-tools">
            {sel.tools.map((t: OpenArtTool) => (
              <div className="oa-tool" key={t.name}>
                <div className="oa-tool-h">
                  <code>{t.cli}</code>
                  {t.required_inputs.length > 0 && (
                    <span className="oa-req">needs {t.required_inputs.map((i) => i.split('_').join(' ')).join(', ')}</span>
                  )}
                </div>
                <p>{t.description}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      <p className="oa-foot">
        Prerequisite: a Chromium instance with <code>--remote-debugging-port=9222</code> and a signed-in profile,
        then <code>node tools/rea/run.mjs list-browser-targets --cdp-endpoint http://127.0.0.1:9222</code> to start.
        Full machine-readable plan: <code>docs/research/open-art/pipeline.json</code>.
      </p>
    </div>
  );
}
